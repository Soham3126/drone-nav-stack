#!/usr/bin/env python3
"""Make the simulated drone collide like the airframe the guidebook plans for.

Why: the planner, the clearance metric and every test treat the drone as a
0.27 m circle (guidebook 4.4: 360 mm wheelbase + 7-inch propellers). The
Gazebo iris body already fits that circle (its collision mesh reaches 0.272 m),
but each of its four propellers has a 0.10 m collision disc centred 0.24-0.26 m
from the middle, so the propeller edges reach 0.355 m. In I2 (run 20261117_012742)
a propeller disc caught a wall corner while the body was 0.34 m from it - legal
for a 0.27 m drone - and the friction spun the drone into the wall.

What: copies ardupilot_gazebo's iris_with_standoffs and iris_with_ardupilot from
the installed checkout, changing only
  * each propeller's collision radius, so its edge stays inside 0.27 m, and
  * the include in iris_with_ardupilot, so it uses the copy above.
Model names inside the files are unchanged, so every joint and plugin name
(iris_with_standoffs::rotor_0_joint, ...) is the same as before; meshes still come
from the original folder. Flight behaviour (mass, inertia, lift, motors) is
untouched: collision shapes only matter when something touches.

Usage:  python3 make_compact_iris.py [--src ~/ardupilot_gazebo/models] [--out <drone_sim>/models]
        python3 make_compact_iris.py --check     # exit 1 if the copies are missing
"""
import argparse
import math
import os
import re
import sys

ROBOT_R = 0.27
MIN_DISC = 0.005
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.normpath(os.path.join(HERE, '..', 'models'))
STANDOFFS = 'iris_compact_standoffs'
ARDUPILOT = 'iris_compact_ardupilot'

CONFIG = """<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>Generated by drone_sim/tools/make_compact_iris.py from ardupilot_gazebo's {orig}.
    Only the propeller collision discs (and the include) differ; see that script.</description>
</model>
"""

NOTE = ('<!-- GENERATED by drone_sim/tools/make_compact_iris.py from ardupilot_gazebo/models/{orig}.\n'
        '     Do not edit; re-run the script instead. Change: {change} -->\n')


def compact_standoffs(text):
    """Shrink each rotor link's collision cylinder radius. Returns (text, [(rotor, old, new)])."""
    changes = []
    out = []
    pos = 0
    for m in re.finditer(r"<link name=['\"](rotor_\d)['\"]>(.*?)</link>", text, re.S):
        name, body = m.group(1), m.group(2)
        pm = re.search(r'<pose>\s*([-\d.eE]+)\s+([-\d.eE]+)', body)
        cm = re.search(r'(<collision\b.*?<radius>)\s*([\d.eE]+)\s*(</radius>)', body, re.S)
        if not pm or not cm:
            raise SystemExit(f'{name}: could not find its pose or collision radius')
        reach = math.hypot(float(pm.group(1)), float(pm.group(2)))
        old = float(cm.group(2))
        new = max(MIN_DISC, round(ROBOT_R - reach, 3))
        new = min(new, old)
        body2 = body[:cm.start(2)] + f'{new}' + body[cm.end(2):]
        out.append(text[pos:m.start(2)])
        out.append(body2)
        pos = m.end(2)
        changes.append((name, round(reach, 3), old, new))
    out.append(text[pos:])
    if len(changes) != 4:
        raise SystemExit(f'expected 4 rotor links, found {len(changes)}')
    return ''.join(out), changes


def add_note(text, note):
    i = text.find('?>')
    i = i + 2 if i >= 0 else 0
    return text[:i] + '\n' + note + text[i:].lstrip('\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', default=os.path.expanduser('~/ardupilot_gazebo/models'))
    ap.add_argument('--out', default=DEFAULT_OUT)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()

    targets = [os.path.join(a.out, n, 'model.sdf') for n in (STANDOFFS, ARDUPILOT)]
    if a.check:
        missing = [t for t in targets if not os.path.isfile(t)]
        if missing:
            print('compact iris missing:', ', '.join(missing), '- run drone_sim/tools/make_compact_iris.py')
            sys.exit(1)
        print('compact iris present')
        return

    src_s = os.path.join(a.src, 'iris_with_standoffs', 'model.sdf')
    src_a = os.path.join(a.src, 'iris_with_ardupilot', 'model.sdf')
    for p in (src_s, src_a):
        if not os.path.isfile(p):
            raise SystemExit(f'not found: {p} (pass --src <ardupilot_gazebo>/models)')

    s_text, changes = compact_standoffs(open(src_s).read())
    s_text = add_note(s_text, NOTE.format(orig='iris_with_standoffs',
                                          change='propeller collision radii ' + ', '.join(
                                              f'{n} {o}->{nw} m' for n, _, o, nw in changes)))

    a_text = open(src_a).read()
    inc = '<uri>model://iris_with_standoffs</uri>'
    if a_text.count(inc) != 1:
        raise SystemExit(f'expected exactly one "{inc}" in {src_a}, found {a_text.count(inc)}')
    a_text = a_text.replace(inc, f'<uri>model://{STANDOFFS}</uri>')
    a_text = add_note(a_text, NOTE.format(orig='iris_with_ardupilot',
                                          change=f'includes model://{STANDOFFS} instead of iris_with_standoffs'))

    for name, orig, text in ((STANDOFFS, 'iris_with_standoffs', s_text), (ARDUPILOT, 'iris_with_ardupilot', a_text)):
        d = os.path.join(a.out, name)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, 'model.sdf'), 'w') as f:
            f.write(text)
        with open(os.path.join(d, 'model.config'), 'w') as f:
            f.write(CONFIG.format(name=name, orig=orig))

    for n, reach, o, nw in changes:
        print(f'{n}: centre {reach:.3f} m from the middle, disc {o} -> {nw} m, edge {reach + o:.3f} -> {reach + nw:.3f} m')
    print('wrote', ', '.join(targets))


if __name__ == '__main__':
    main()
